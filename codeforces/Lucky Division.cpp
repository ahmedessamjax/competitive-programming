void solve() {
  set<int> numbers = {4, 7, 44, 47, 74, 77 , 444, 447, 474, 477,
  744, 747, 777};
  int n ; cin >> n;
  for(auto i : numbers){
    if(n % i == 0){
      cout << "YES\n"; return;
    }
  }
  cout << "NO\n";
}

